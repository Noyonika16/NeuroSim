"""Train a transparent linear readout over the frozen connectome voltage state.

Run after `node benchmark/collect_flappy_decoder.js`.
The assisted controller supplies labels during offline calibration only. At runtime
web/app.js uses neuron voltages only and never reads game geometry for the action.
"""
from pathlib import Path
import json
import numpy as np
from sklearn.model_selection import GroupShuffleSplit
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, precision_score, recall_score, confusion_matrix

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "benchmark" / "flappy_readout_training.jsonl"
MODEL_JSON = ROOT / "web" / "flappy_decoder.json"
MODEL_JS = ROOT / "web" / "flappy_decoder.js"

if not DATA.exists():
    raise SystemExit("Training data not found. First run: node benchmark/collect_flappy_decoder.js")

rows = [json.loads(line) for line in DATA.read_text(encoding="utf-8").splitlines() if line.strip()]
X = np.asarray([r["features"] for r in rows], dtype=np.float32)
y = np.asarray([r["target"] for r in rows], dtype=np.int32)
groups = np.asarray([r["seed"] for r in rows])
if X.shape[1] != 302:
    raise SystemExit(f"Expected 302 neuron-voltage features, got {X.shape[1]}")

connectome = json.loads((ROOT / "web" / "connectome_data.json").read_text(encoding="utf-8"))
all_feature_names = sorted(connectome["neurons"].keys())
prefixes = (
    "ASH", "CEP", "ALM", "AVM", "ASE", "AVA", "AVB", "AVD", "AVE", "PVC",
    "DB", "VB", "DA", "VA", "DD", "VD", "SMDD", "SMDV", "SMBD", "SMBV",
    "SABD", "SABV", "RMD", "RMDD", "RMED", "RMEL", "RMEV"
)
feature_indices = [i for i, name in enumerate(all_feature_names) if name.startswith(prefixes)]
feature_names = [all_feature_names[i] for i in feature_indices]
X = X[:, feature_indices]

splitter = GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=42)
train_idx, test_idx = next(splitter.split(X, y, groups))
scaler = StandardScaler()
X_train = scaler.fit_transform(X[train_idx])
X_test = scaler.transform(X[test_idx])
model = LogisticRegression(C=0.1, max_iter=1000)
model.fit(X_train, y[train_idx])

probs = model.predict_proba(X_test)[:, 1]
threshold = 0.40
pred = (probs >= threshold).astype(np.int32)
tn, fp, fn, tp = confusion_matrix(y[test_idx], pred, labels=[0, 1]).ravel()
precision = float(precision_score(y[test_idx], pred, zero_division=0))
recall = float(recall_score(y[test_idx], pred, zero_division=0))
result = {
    "version": "v13-trained-linear-readout",
    "method": "L2-regularized logistic regression over sensory, command-interneuron, and motor-neuron voltage features",
    "connectome_weights_frozen": True,
    "runtime_game_state_access": False,
    "feature_names": feature_names,
    "mean": scaler.mean_.astype(float).tolist(),
    "scale": np.where(scaler.scale_ > 1e-8, scaler.scale_, 1.0).astype(float).tolist(),
    "weights": model.coef_[0].astype(float).tolist(),
    "bias": float(model.intercept_[0]),
    "threshold": threshold,
    "training_seed_count": int(len(set(groups[train_idx]))),
    "heldout_seed_count": int(len(set(groups[test_idx]))),
    "heldout_metrics": {
        "average_precision": float(average_precision_score(y[test_idx], probs)),
        "precision_at_threshold": precision,
        "recall_at_threshold": recall,
        "threshold": threshold,
        "tp": int(tp), "fp": int(fp), "fn": int(fn), "tn": int(tn),
        "positive_rate": float(y[test_idx].mean())
    },
    "notes": "The connectome dynamics and synaptic weights remain frozen. This readout uses the simulated sensory, command-interneuron, and motor-neuron voltage subset and is trained to imitate the assisted policy. Held-out action imitation does not establish biological validity."
}
MODEL_JSON.write_text(json.dumps(result, separators=(",", ":")), encoding="utf-8")
MODEL_JS.write_text(
    "/* Generated by benchmark/train_flappy_decoder.py. */\\nwindow.FLAPPY_DECODER = "
    + json.dumps(result, separators=(",", ":")) + ";\\n",
    encoding="utf-8"
)
print(json.dumps({
    "rows": int(len(rows)),
    "train_seeds": result["training_seed_count"],
    "heldout_seeds": result["heldout_seed_count"],
    "heldout_metrics": result["heldout_metrics"],
    "written": [str(MODEL_JSON), str(MODEL_JS)]
}, indent=2))
