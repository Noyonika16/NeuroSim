"""Train an offline linear turn readout over frozen connectome voltage features.

Targets are assisted-controller turn deltas; runtime inference uses neuron
voltages only. This is teacher distillation, not a biologically learned policy. Runtime turn output is clipped to +/-0.045 rad/frame for conservative curvature.
"""
from pathlib import Path
import json
import numpy as np
from sklearn.model_selection import GroupShuffleSplit
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import Ridge
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "benchmark" / "chemotaxis_readout_training.jsonl"
MODEL_JSON = ROOT / "web" / "chemotaxis_decoder.json"
MODEL_JS = ROOT / "web" / "chemotaxis_decoder.js"
if not DATA.exists():
    raise SystemExit("Training data not found. Run: node benchmark/collect_chemotaxis_decoder.js")
rows = [json.loads(line) for line in DATA.read_text(encoding="utf-8").splitlines() if line.strip()]
X_all = np.asarray([r["features"] for r in rows], dtype=np.float32)
y = np.asarray([r["target"] for r in rows], dtype=np.float32)
groups = np.asarray([r["seed"] for r in rows])
if X_all.shape[1] != 302:
    raise SystemExit(f"Expected 302 voltage features, got {X_all.shape[1]}")
connectome = json.loads((ROOT / "web" / "connectome_data.json").read_text(encoding="utf-8"))
all_names = sorted(connectome["neurons"].keys())
prefixes = ("ASH", "CEP", "ALM", "AVM", "ASE", "AWC", "AWA", "AWB", "AWC", "AVA", "AVB", "AVD", "AVE", "PVC", "DB", "VB", "DA", "VA", "DD", "VD", "SMDD", "SMDV", "SMBD", "SMBV", "SABD", "SABV", "RMD", "RMDD", "RMED", "RMEL", "RMEV")
indices = [i for i, name in enumerate(all_names) if name.startswith(prefixes)]
feature_names = [all_names[i] for i in indices]
X = X_all[:, indices]
splitter = GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=43)
train_idx, test_idx = next(splitter.split(X, y, groups))
scaler = StandardScaler()
X_train = scaler.fit_transform(X[train_idx])
X_test = scaler.transform(X[test_idx])
model = Ridge(alpha=20.0)
model.fit(X_train, y[train_idx])
pred = np.clip(model.predict(X_test), -0.045, 0.045)
result = {
    "version": "v13-trained-chemotaxis-turn-readout",
    "method": "Ridge regression over selected sensory, command-interneuron, and motor-neuron voltage features",
    "connectome_weights_frozen": True,
    "runtime_food_bearing_access": False,
    "training_target": "assisted reference angular correction, clipped to +/-0.10 rad per frame",
    "feature_names": feature_names,
    "mean": scaler.mean_.astype(float).tolist(),
    "scale": np.where(scaler.scale_ > 1e-8, scaler.scale_, 1.0).astype(float).tolist(),
    "weights": model.coef_.astype(float).tolist(),
    "bias": float(model.intercept_),
    "max_turn_radians": 0.10,
    "runtime_turn_limit_radians": 0.045,
    "training_seed_count": int(len(set(groups[train_idx]))),
    "heldout_seed_count": int(len(set(groups[test_idx]))),
    "heldout_metrics": {
        "mae_radians_runtime_clipped": float(mean_absolute_error(y[test_idx], pred)),
        "rmse_radians_runtime_clipped": float(mean_squared_error(y[test_idx], pred) ** 0.5),
        "r2_runtime_clipped": float(r2_score(y[test_idx], pred)),
        "heldout_rows": int(len(test_idx)),
        "target_std_radians": float(np.std(y[test_idx]))
    },
    "notes": "Trained to imitate assisted-policy turn corrections from neural voltage features after synthetic temporal and bilateral sensory encoding. The model is not zero-shot and is not a validated biological controller."
}
MODEL_JSON.write_text(json.dumps(result, separators=(",", ":")), encoding="utf-8")
MODEL_JS.write_text("/* Generated by benchmark/train_chemotaxis_decoder.py. */\nwindow.CHEMOTAXIS_DECODER = " + json.dumps(result, separators=(",", ":")) + ";\n", encoding="utf-8")
print(json.dumps({"rows": len(rows), "train_seeds": result["training_seed_count"], "heldout_seeds": result["heldout_seed_count"], "heldout_metrics": result["heldout_metrics"], "written": [str(MODEL_JSON), str(MODEL_JS)]}, indent=2))
